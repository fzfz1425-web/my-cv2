/* =========================
   ELEMENTS
========================= */

const langToggle = document.getElementById("langToggle");
const themeToggle = document.getElementById("themeToggle");
const themeIcon = themeToggle.querySelector(".theme-icon");

const menuToggle = document.getElementById("menuToggle");
const nav = document.querySelector(".desktop-nav");

const body = document.body;


/* =========================
   LANGUAGE
========================= */

let currentLang = "ar";

function setLanguage(lang) {
  if (!translations[lang]) return;

  currentLang = lang;

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  body.setAttribute("lang", lang);
  body.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;

    if (
      Object.prototype.hasOwnProperty.call(
        translations[lang],
        key
      )
    ) {
      element.innerHTML = translations[lang][key];
    }
  });

  // الاسم الشخصي
  const personName = document.querySelector(".hero-name");

  if (personName) {
    personName.innerHTML = `${translations[lang].personName}<span>.</span>`;
  }

  // زر اللغة
  langToggle.innerHTML = lang === "ar"
    ? 'EN <span>↗</span>'
    : 'عربي <span>↗</span>';

  langToggle.setAttribute(
    "aria-label",
    lang === "ar" ? "Switch to English" : "التبديل إلى العربية"
  );

  // عنوان الصفحة
  document.title = lang === "ar"
    ? "فايزة أحمد | الملف الشخصي"
    : "Faiza Ahmed | Portfolio";

  // تحديث وصف الصفحة
  document.querySelector('meta[name="description"]')
    .setAttribute(
      "content",
      lang === "ar"
        ? "الملف الشخصي لفايزة أحمد، طالبة نظم المعلومات الإدارية ومهتمة بالتقنية والبيانات والابتكار."
        : "Faiza Ahmed's portfolio. Management Information Systems student interested in technology, data, and innovation."
    );

  updateThemeButton();
  updateMenuLabel();

  try {
    localStorage.setItem("portfolio-language", lang);
  } catch (error) {
    console.warn("Language preference could not be saved.");
  }
}

langToggle.addEventListener("click", () => {
  setLanguage(currentLang === "ar" ? "en" : "ar");
});


/* =========================
   THEME
========================= */

function setTheme(theme) {
  const selectedTheme = theme === "dark" ? "dark" : "light";

  body.setAttribute("data-theme", selectedTheme);

  updateThemeButton();

  try {
    localStorage.setItem("portfolio-theme", selectedTheme);
  } catch (error) {
    console.warn("Theme preference could not be saved.");
  }
}

function updateThemeButton() {
  const isDark = body.getAttribute("data-theme") === "dark";

  // رمز فقط دون كلمة ظاهرة
  themeIcon.textContent = isDark ? "☀" : "☾";

  const accessibleLabel = isDark
    ? translations[currentLang].themeLight
    : translations[currentLang].themeDark;

  themeToggle.setAttribute("aria-label", accessibleLabel);
  themeToggle.setAttribute("title", accessibleLabel);
}

themeToggle.addEventListener("click", () => {
  const currentTheme = body.getAttribute("data-theme");

  setTheme(currentTheme === "dark" ? "light" : "dark");
});


/* =========================
   MOBILE MENU
========================= */

function closeMenu() {
  nav.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
  updateMenuLabel();
}

function updateMenuLabel() {
  const isOpen = menuToggle.getAttribute("aria-expanded") === "true";

  menuToggle.setAttribute(
    "aria-label",
    isOpen
      ? translations[currentLang].menuClose
      : translations[currentLang].menuOpen
  );
}

menuToggle.addEventListener("click", () => {
  const opened = nav.classList.toggle("open");

  menuToggle.setAttribute("aria-expanded", String(opened));
  updateMenuLabel();
});

nav.querySelectorAll("a").forEach(link => {
  link.addEventListener("click", closeMenu);
});

document.addEventListener("keydown", event => {
  if (event.key === "Escape") {
    closeMenu();
  }
});

document.addEventListener("click", event => {
  const clickedInsideNav = nav.contains(event.target);
  const clickedMenuButton = menuToggle.contains(event.target);

  if (!clickedInsideNav && !clickedMenuButton) {
    closeMenu();
  }
});


/* =========================
   FOOTER YEAR
========================= */

document.getElementById("year").textContent =
  new Date().getFullYear();


/* =========================
   RESTORE PREFERENCES
========================= */

let savedLanguage = "ar";
let savedTheme = "light";

try {
  savedLanguage = localStorage.getItem("portfolio-language") || "ar";
  savedTheme = localStorage.getItem("portfolio-theme") || "light";
} catch (error) {
  console.warn("Saved preferences could not be loaded.");
}

setTheme(savedTheme);
setLanguage(savedLanguage);
